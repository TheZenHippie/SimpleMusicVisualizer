namespace SimpleMusicVisualizer.UI;

/// <summary>
/// Defines the available cyberpunk audio visualization render modes.
/// </summary>
public enum VisualizerMode
{
    /// <summary>
    /// Classic vertical neon bars with gravity peak caps and floor mirror reflection.
    /// </summary>
    SpectrumBars,

    /// <summary>
    /// Circular radiating neon ring with pulsing bass core and orbiting accents.
    /// </summary>
    RadialIris,

    /// <summary>
    /// Glowing oscilloscope wave ribbon with chromatic aberration and phosphor persistence.
    /// </summary>
    LaserRibbon
}
